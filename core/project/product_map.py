"""Master product map for StructuralPro.

This is a planning/architecture registry, not a claim that every leaf is already
implemented. Existing executable capabilities remain owned by their current
modules; this map provides a stable whole-product destination without replacing
or removing them.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Final


@dataclass(frozen=True)
class ProductNode:
    key: str
    title: str
    children: tuple["ProductNode", ...] = ()


def _n(key: str, title: str, *children: ProductNode) -> ProductNode:
    return ProductNode(key, title, tuple(children))


