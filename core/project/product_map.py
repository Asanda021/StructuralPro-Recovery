def flatten_product_map(node: ProductNode = MASTER_PRODUCT_MAP) -> tuple[ProductNode, ...]:
    """Return all nodes depth-first, including the root."""
    result: list[ProductNode] = []

    def walk(current: ProductNode) -> None:
        result.append(current)
        for child in current.children:
            walk(child)

    walk(node)
    return tuple(result)


def find_product_node(key: str) -> ProductNode | None:
    """Find a node by stable product-map key."""
    wanted = str(key or "").strip()
    return next((node for node in flatten_product_map() if node.key == wanted), None)
