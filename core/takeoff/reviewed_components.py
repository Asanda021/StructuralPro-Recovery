"""Reusable, source-backed concrete/formwork/reinforcement quantities.

Every measured part is entered explicitly; no dimension, bar count, hook/lap
allowance, concrete overlap or surface is generated by the software.
"""
from __future__ import annotations

import math
from decimal import Decimal, InvalidOperation, Inexact, Rounded, localcontext
from typing import Any

PARTS = frozenset({"straight", "bend", "hook", "anchorage", "lap", "other"})


def positive(value: Any, name: str, *, allow_zero: bool = False, integer: bool = False) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{name}: مقدار عددی معتبر لازم است")
    try:
        result = float(value)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"{name}: مقدار عددی معتبر لازم است") from exc
    if not math.isfinite(result) or result < 0 or (result == 0 and not allow_zero):
        raise ValueError(f"{name}: مقدار مثبت و متناهی لازم است")
    if result == 0.0:
        try:
            if Decimal(str(value)) != 0:
                raise ValueError(f"{name}: مقدار غیرصفر در تبدیل عددی به صفر تبدیل شده است")
        except InvalidOperation as exc:
            raise ValueError(f"{name}: مقدار عددی معتبر لازم است") from exc
    if integer:
        try:
            exact_integer = result.is_integer() and Decimal(str(value)) == Decimal(int(result))
        except (InvalidOperation, ValueError, OverflowError):
            exact_integer = False
        if not exact_integer:
            raise ValueError(f"{name}: مقدار باید عدد صحیح بدون گردشدن باشد")
    return result


def require_text(value: Any, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} الزامی است")
    return value.strip()



def _exact_float_sum(values):
    """Aggregate normalized decimal values, then use the existing loss-rejecting bridge."""
    from core.commercial.statement_amendment import legacy_float
    with localcontext() as ctx:
        ctx.prec = 1024
        ctx.traps[Inexact] = True
        ctx.traps[Rounded] = True
        total = sum((Decimal(str(value)) for value in values), Decimal(0))
    return legacy_float(total)

def cut_length(segment: dict[str, Any]) -> tuple[float, dict[str, Any]]:
    """Return verified length only from a direct approval OR a complete parts list.

    Parts are actual lengths, not inferred coefficients for hooks/anchorage.
    The bar is never lengthened by assumed anchorage or arbitrary percentage.
    """
    if not isinstance(segment, dict):
        raise ValueError("دیتایل میلگرد معتبر نیست")
    require_text(segment.get("source_ref"), "مرجع دیتایل میلگرد")
    direct = "cut_length_m" in segment
    parts = "length_parts_m" in segment
    if direct == parts:
        raise ValueError("طول برش باید دقیقاً با یکی از دو روش معتبر ثبت شود")
    if direct:
        length = positive(segment["cut_length_m"], "طول برش تأییدشده")
        require_text(segment.get("approved_by"), "تأییدکننده طول برش")
        return length, {"method": "approved_cut_length", "cut_length_m": length,
                        "source_ref": segment["source_ref"], "approved_by": segment["approved_by"]}
    pieces = segment["length_parts_m"]
    if not isinstance(pieces, list) or not pieces:
        raise ValueError("اجزای طول برش ناقص است")
    checked: list[dict[str, Any]] = []
    has_straight = False
    for piece in pieces:
        if not isinstance(piece, dict) or piece.get("kind") not in PARTS:
            raise ValueError("نوع جزء طول برش معتبر نیست")
        length = positive(piece.get("length_m"), "طول جزء میلگرد")
        ref = require_text(piece.get("source_ref"), "مرجع جزء میلگرد")
        checked.append({"kind": piece["kind"], "length_m": length, "source_ref": ref})
        if piece["kind"] == "straight":
            has_straight = True
    if not has_straight:
        raise ValueError("طول مستقیم میلگرد صریح ثبت نشده است")
    approved = require_text(segment.get("approved_by"), "تأییدکننده اجزای طول برش")
    total = _exact_float_sum(part["length_m"] for part in checked)
    positive(total, "طول کل برش")
    return total, {"method": "approved_parts", "length_parts_m": checked,
                   "cut_length_m": total, "source_ref": segment["source_ref"],
                   "approved_by": approved}


def reviewed_steel(group: dict[str, Any], *, label: str, engine: Any) -> tuple[float, list[dict]]:
    if not isinstance(group, dict) or group.get("status") != "confirmed":
        raise ValueError(f"{label}: نیازمند تأیید است")
    approved = require_text(group.get("approved_by"), f"تأییدکننده {label}")
    require_text(group.get("source_ref"), f"مرجع {label}")
    series = group.get("segments")
    if not isinstance(series, list) or not series:
        raise ValueError(f"{label}: حداقل یک سری مستقل لازم است")
    weights = []
    evidence = []
    for segment in series:
        if not isinstance(segment, dict):
            raise ValueError("ساختار سری میلگرد نامعتبر است")
        count = int(positive(segment.get("count"), "تعداد میلگرد", integer=True))
        unit_mass = positive(segment.get("unit_weight_kg_m"), "وزن واحد مستند میلگرد")
        require_text(segment.get("unit_weight_source"), "منبع وزن واحد میلگرد")
        length, parts = cut_length(segment)
        result = engine.calculate("building", "rebar", description=label,
                                  length=length, unit_weight=unit_mass, count=count)
        weights.append(result.quantity)
        evidence.append({"count": count, "unit_weight_kg_m": unit_mass,
                         "unit_weight_source": segment["unit_weight_source"],
                         "cut": parts, "approved_by": approved})
    mass = _exact_float_sum(weights)
    positive(mass, f"وزن {label}")
    return mass, evidence


def net_concrete(gross_m3: float, intersections: list[dict]) -> tuple[float, list[dict]]:
    positive(gross_m3, "حجم ناخالص بتن")
    if not isinstance(intersections, list):
        raise ValueError("فهرست کسورات بتن نامعتبر است")
    checked = []
    ids = set()
    for item in intersections:
        if not isinstance(item, dict):
            raise ValueError("کسر حجم باید ساختار معتبر داشته باشد")
        ident = require_text(item.get("id"), "شناسه کسر مشترک")
        if ident in ids:
            raise ValueError("هم‌پوشانی بتن با شناسه تکراری ثبت شده است")
        ids.add(ident)
        volume = positive(item.get("volume_m3"), "حجم کسر مستند")
        ref = require_text(item.get("source_ref"), "مرجع کسر")
        approved = require_text(item.get("approved_by"), "تأییدکننده کسر")
        checked.append({"id": ident, "volume_m3": volume, "source_ref": ref,
                        "approved_by": approved})
    deduction = _exact_float_sum(x["volume_m3"] for x in checked)
    # Gross volume is an existing float-engine result; retain its established
    # subtraction semantics, while rejecting a nonzero deduction lost entirely.
    net = gross_m3 - deduction
    if deduction > 0 and net == gross_m3:
        raise ValueError("کسر غیرصفر در دقت مسیر عددی قدیمی قابل اعمال نیست")
    positive(net, "حجم خالص بتن")
    return net, checked


def net_formwork(formwork: dict) -> tuple[float, list[dict]]:
    """Areas are net physical contact faces, not inferred perimeter*height."""
    if not isinstance(formwork, dict):
        raise ValueError("قالب‌بندی باید ساختار معتبر داشته باشد")
    require_text(formwork.get("approved_by"), "تأییدکننده قالب‌بندی")
    faces = formwork.get("surfaces")
    if not isinstance(faces, list) or not faces:
        raise ValueError("سطوح قالب‌بندی تأییدشده الزامی است")
    seen = set()
    checked = []
    for item in faces:
        if not isinstance(item, dict):
            raise ValueError("ساختار سطح قالب‌بندی نامعتبر است")
        face_id = require_text(item.get("id"), "شناسه سطح قالب")
        if face_id in seen:
            raise ValueError("سطح قالب‌بندی تکراری است")
        seen.add(face_id)
        area = positive(item.get("net_area_m2"), "مساحت واقعی سطح قالب")
        ref = require_text(item.get("source_ref"), "مرجع سطح قالب")
        checked.append({"id": face_id, "net_area_m2": area, "source_ref": ref})
    return _exact_float_sum(x["net_area_m2"] for x in checked), checked
