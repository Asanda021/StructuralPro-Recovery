"""Read-only original DWG independent-decoder probe. NEVER approves quantities.

Probe the original DWG bytes with a pinned, independently implemented reader,
not with a DXF generated by an already defective converter. A high-level DWG
reader cannot by itself establish proprietary class/payload completeness.

Safe for diagnostic use only. No byte changes, unit inference, format repair,
user-content submission, or financial acceptance.
"""
from __future__ import annotations

from collections import Counter
from hashlib import sha256
from importlib import import_module, metadata
import json
from pathlib import Path
from typing import Any

SUPPORTED_SIGNATURES = frozenset({b'AC1015', b'AC1018', b'AC1021', b'AC1024', b'AC1027', b'AC1032'})
MAX_DWG_BYTES = 50 * 1024 * 1024
MAX_ENTITIES = 1_000_000
REQUIRED_DECODER = 'ezdwg'
REQUIRED_DECODER_VERSION = '0.17.0'


def _failure(result: dict[str, Any], reason: str, *, detail: str = '') -> dict[str, Any]:
    result['status'] = 'BLOCKED_NO_INDEPENDENT_DECODER'
    result['reason'] = reason
    if detail:
        result['detail'] = detail[:250]
    return result


def _handle(value: object) -> int:
    if isinstance(value, bool):
        raise ValueError('boolean handle')
    if isinstance(value, int):
        result = value
    elif isinstance(value, str):
        stripped = value.strip()
        if not stripped or any(c not in '0123456789ABCDEFabcdef' for c in stripped):
            raise ValueError('non-hex handle')
        result = int(stripped, 16)
    else:
        raise ValueError('unreadable handle')
    if not 0 < result < 2**64:
        raise ValueError('handle outside allowed positive range')
    return result


def probe_original_dwg(source: str | Path) -> dict[str, Any]:
    """Attempt to inventory native ModelSpace without accepting opaque payloads.

    Source identity is checked before and after decoding. Explicitly *never*
    assert independent full-class coverage, even when all supported entities
    decode and modelspace count matches LibreDWG.
    """
    result: dict[str, Any] = {
        'policy': 'structuralpro_p8p2_native_probe_v1',
        'read_only': True,
        'independent_original_dwg_input': True,
        'independent_decoder_executed': False,
        'full_source_object_graph_verified': False,
        'opaque_class_payloads_verified': False,
        'shx_glyphs_verified': False,
        'unit_and_revision_verified': False,
        'geometry_approved_for_financial_takeoff': False,
        'approved_quantities': 0,
        'status': 'BLOCKED_NO_INDEPENDENT_DECODER',
    }
    path = Path(source)
    if not path.is_file() or path.suffix.lower() != '.dwg':
        return _failure(result, 'ORIGINAL_DWG_NOT_FOUND')
    stat_before = path.stat()
    if not 6 < stat_before.st_size <= MAX_DWG_BYTES:
        return _failure(result, 'SOURCE_FILE_SIZE_INVALID')
    data = path.read_bytes()
    signature = data[:6]
    result.update({'source_sha256': sha256(data).hexdigest(),
                   'source_size_bytes': len(data),
                   'source_dwg_signature': signature.decode('ascii', errors='replace')})
    if signature not in SUPPORTED_SIGNATURES:
        return _failure(result, 'DWG_HEADER_UNSUPPORTED')
    # A string directly present in the compressed DWG does not prove an object
    # exists or that its payload is valid; this is only byte-level corroboration.
    result['native_raw_ascii_anchors'] = {
        'AEC_VARS_DWG_SETUP': {'occurrences': data.count(b'AEC_VARS_DWG_SETUP'),
                               'first_offset': data.find(b'AEC_VARS_DWG_SETUP')},
    }
    try:
        version = metadata.version(REQUIRED_DECODER)
    except metadata.PackageNotFoundError:
        return _failure(result, 'PINNED_EZDWG_NOT_INSTALLED')
    result['decoder_package'] = REQUIRED_DECODER
    result['decoder_version'] = version
    if version != REQUIRED_DECODER_VERSION:
        return _failure(result, 'DECODER_VERSION_NOT_PINNED')
    try:
        module = import_module(REQUIRED_DECODER)
        reader = getattr(module, 'read')
        native = reader(str(path))
        if native.version != result['source_dwg_signature']:
            return _failure(result, 'NATIVE_READER_VERSION_MISMATCH')
        msp = native.modelspace()
        roster: set[tuple[int, str]] = set()
        handles: set[int] = set()
        kinds: Counter[str] = Counter()
        for entity in msp.iter_entities():
            if len(roster) >= MAX_ENTITIES:
                return _failure(result, 'NATIVE_MODELSPACE_EXCEEDS_LIMIT')
            handle = _handle(entity.handle)
            kind = str(entity.dxftype).strip().upper()
            if not kind or handle in handles:
                return _failure(result, 'DUPLICATE_OR_INVALID_SOURCE_ENTITY')
            handles.add(handle)
            roster.add((handle, kind))
            kinds[kind] += 1
        sorted_roster = sorted(roster)
        digest = sha256(''.join(f'{handle:X}\t{kind}\n' for handle, kind in sorted_roster).encode('utf-8')).hexdigest()
        stat_after = path.stat()
        if (stat_before.st_dev, stat_before.st_ino, stat_before.st_size, stat_before.st_mtime_ns) != (
            stat_after.st_dev, stat_after.st_ino, stat_after.st_size, stat_after.st_mtime_ns
        ) or sha256(path.read_bytes()).hexdigest() != result['source_sha256']:
            return _failure(result, 'SOURCE_CHANGED_DURING_READ')
        result.update({
            'independent_decoder_executed': True,
            'native_modelspace_entity_count': len(roster),
            'native_modelspace_by_type': dict(sorted(kinds.items())),
            'native_modelspace_handle_type_sha256': digest,
            'native_declared_units': native.units,
            'status': 'PARTIAL_NO_GO',
            'reason': 'HIGH_LEVEL_ROSTER_NOT_A_FULL_OPAQUE_CLASS_AND_PAYLOAD_ORACLE',
        })
        return result
    except Exception as exc:  # Never mark a partial native read as a success.
        return _failure(result, 'INDEPENDENT_DECODER_FAILED', detail=type(exc).__name__)


def save_probe_report(source: str | Path, output_path: str | Path) -> dict[str, Any]:
    """Writes a diagnostic JSON file only, never changes the original DWG."""
    record = probe_original_dwg(source)
    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(record, ensure_ascii=False, sort_keys=True, indent=2) + '\n', encoding='utf-8')
    return record